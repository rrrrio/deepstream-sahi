/*
 * File: gstnvsahipreprocess.c
 * Description: GstBin wrapping nvdspreprocess that dynamically generates SAHI ROI
 *              config from slice parameters. No static config file required.
 *
 *              Pipeline position: streammux → nvsahipreprocess → nvinfer
 *
 *              Properties:
 *                slice-width, slice-height  — tile dimensions
 *                overlap-h, overlap-v       — fractional overlap [0,1)
 *                frame-width, frame-height  — source resolution
 *
 * Author: Yuhao Ding
 */

#include "gstnvsahipreprocess.h"
#include "sahi_roi.h"

#include <stdio.h>
#include <string.h>
#include <gst/gst.h>

GST_DEBUG_CATEGORY_STATIC(gst_nvsahipreprocess_debug);
#define GST_CAT_DEFAULT gst_nvsahipreprocess_debug

