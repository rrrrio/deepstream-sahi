# ─── SAHI ROI computation ─────────────────────────────────────────────


def compute_sahi_rois(
    frame_w: int,
    frame_h: int,
    slice_w: int,
    slice_h: int,
    overlap_h: float = 0.2,
    overlap_v: float = 0.2,
) -> List[Tuple[int, int, int, int]]:
    """Compute SAHI ROI grid as list of (left, top, width, height).

    Uses stride = slice_size - int(slice_size * overlap) to match
    nvdspreprocess convention. The last ROI is always the full frame.
    """
    stride_x = max(1, slice_w - int(slice_w * overlap_h))
    stride_y = max(1, slice_h - int(slice_h * overlap_v))

    xs = [x for x in range(0, frame_w - slice_w + 1, stride_x)]
    edge_x = frame_w - slice_w
    if edge_x >= 0 and (not xs or xs[-1] != edge_x):
        xs.append(edge_x)

    ys = [y for y in range(0, frame_h - slice_h + 1, stride_y)]
    edge_y = frame_h - slice_h
    if edge_y >= 0 and (not ys or ys[-1] != edge_y):
        ys.append(edge_y)

    rois = [(x, y, slice_w, slice_h) for y in ys for x in xs]
    rois.append((0, 0, frame_w, frame_h))
    return rois


def generate_preprocess_config(
    frame_w: int,
    frame_h: int,
    slice_w: int,
    slice_h: int,
    overlap_h: float = 0.2,
    overlap_v: float = 0.2,
    custom_lib_path: str = DEFAULT_CUSTOM_LIB,
    tensor_name: str = "input",
    pixel_norm: float = 0.00392156862745,
    gpu_id: int = 0,
) -> str:
    """Generate an nvdspreprocess config file dynamically. Returns the temp file path."""
    rois = compute_sahi_rois(frame_w, frame_h, slice_w, slice_h, overlap_h, overlap_v)
    roi_count = len(rois)

    roi_str = ";".join(f"{r[0]};{r[1]};{r[2]};{r[3]}" for r in rois)

    content = (
        f"################################################################################\n"
        f"# Auto-generated by deepstream-sahi (dynamic)\n"
        f"# Frame: {frame_w}x{frame_h}  Slice: {slice_w}x{slice_h}\n"
        f"# Overlap: h={overlap_h:.4f} v={overlap_v:.4f}  ROIs: {roi_count}\n"
        f"################################################################################\n\n"
        f"[property]\n"
        f"enable=1\n"
        f"target-unique-ids=1\n"
        f"network-input-order=0\n"
        f"process-on-frame=1\n"
        f"unique-id=15\n"
        f"gpu-id={gpu_id}\n"
        f"maintain-aspect-ratio=1\n"
        f"symmetric-padding=1\n"
        f"processing-width={slice_w}\n"
        f"processing-height={slice_h}\n"
        f"scaling-buf-pool-size=16\n"
        f"tensor-buf-pool-size=16\n"
        f"network-input-shape={roi_count};3;{slice_h};{slice_w}\n"
        f"network-color-format=0\n"
        f"tensor-data-type=0\n"
        f"tensor-name={tensor_name}\n"
        f"scaling-pool-memory-type=0\n"
        f"scaling-pool-compute-hw=0\n"
        f"scaling-filter=0\n"
        f"custom-lib-path={custom_lib_path}\n"
        f"custom-tensor-preparation-function=CustomTensorPreparation\n\n"
        f"[user-configs]\n"
        f"pixel-normalization-factor={pixel_norm:.14f}\n\n"
        f"[group-0]\n"
        f"src-ids=0\n"
        f"custom-input-transformation-function=CustomAsyncTransformation\n"
        f"process-on-roi=1\n"
        f"draw-roi=0\n"
        f"roi-params-src-0={roi_str}\n"
    )

    tmpdir = tempfile.mkdtemp(prefix="nvsahi_preprocess_")
    config_path = os.path.join(tmpdir, "config_preprocess_sahi.txt")
    with open(config_path, "w") as f:
        f.write(content)
    return config_path


